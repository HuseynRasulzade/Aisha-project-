const icon = (n, cls = '') =>
  `<svg class="ic ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[n] || ''}</svg>`;

const App = (() => {
  const $ = id => document.getElementById(id);
  let lang = 'en';
  try { lang = localStorage.getItem('lang') || 'en'; } catch (e) {}
  const t = k => (I18N[lang] && I18N[lang][k]) || k;
  const hooks = [];
  const origText = new WeakMap();
  let origTitle = document.title;

  const store = {
    get(k, d) { try { const v = localStorage.getItem('sk_' + k); return v == null ? d : JSON.parse(v); } catch (e) { return d; } },
    set(k, v) { try { localStorage.setItem('sk_' + k, JSON.stringify(v)); } catch (e) {} },
  };
  const day = (d = new Date()) => d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
  const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  const NAV = [
    ['home', 'Home', 'index.html', 'home'],
    ['grid', 'Dashboard', 'dashboard.html', 'dashboard'],
    ['book', 'Diary', 'diary.html', 'diary'],
    ['brain', 'AI Plan', 'assistant.html', 'assistant'],
    ['users', 'Community', 'community.html', 'community'],
    ['sparkles', 'Calm', 'calm.html', 'calm'],
    ['heartpulse', 'Health', 'health.html', 'health'],
    ['more', 'More', 'more.html', 'more'],
  ];
  const LANGS = ['en', 'az', 'es', 'fr', 'de', 'ar', 'ru', 'fa'];

  function buildShell() {
    const page = document.body.dataset.page;
    $('app-header').outerHTML = `<div class="lang-float"><select id="lang" aria-label="Language">${LANGS.map(l => `<option value="${l}">${l.toUpperCase()}</option>`).join('')}</select></div>`;
    $('app-footer').outerHTML = `
      <nav class="bottomnav">${NAV.map(n => `<a href="${n[2]}" class="${n[3] === page ? 'on' : ''}"><i>${icon(n[0])}</i><span>${n[1]}</span></a>`).join('')}</nav>`;
    $('lang').onchange = e => setLang(e.target.value);
  }

  function paintIcons() {
    document.querySelectorAll('[data-icon]').forEach(el => { el.innerHTML = icon(el.dataset.icon); el.removeAttribute('data-icon'); });
  }

  function translateDom() {
    const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: n => !n.nodeValue.trim() || n.parentElement.closest('script,style,[data-dyn]')
        ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
    });
    for (let n = w.nextNode(); n; n = w.nextNode()) {
      if (!origText.has(n)) origText.set(n, n.nodeValue);
      const src = origText.get(n), key = src.trim();
      n.nodeValue = src.replace(key, t(key));
    }
    document.querySelectorAll('[data-ph]').forEach(el => { el.placeholder = t(el.dataset.ph); });
    document.title = t(origTitle);
  }

  function setLang(l) {
    lang = l;
    try { localStorage.setItem('lang', l); } catch (e) {}
    document.documentElement.lang = l;
    document.documentElement.dir = (l === 'ar' || l === 'fa') ? 'rtl' : 'ltr';
    const sel = $('lang'); if (sel) sel.value = l;
    hooks.forEach(h => h());
    paintIcons();
    translateDom();
  }

  function start() {
    buildShell();
    paintIcons();
    setLang(lang);
  }

  return { t, store, day, esc, hooks, start, $, setLang, get lang() { return lang; } };
})();
